function csvCell(value: string | number) {
  const t = String(value);
  if (/[",\n]/.test(t)) return `"${t.replace(/"/g, '""')}"`;
  return t;
}

export function kitCsv(items: BomItem[] = ITEMS) {
  const header = [
    "group",
    "name",
    "sku",
    "brand",
    "origin",
    "qty",
    "unit_usd",
    "line_usd",
    "vendor",
    "url",
    "process",
    "material",
    "tier",
  ];
  const rows = items.map((i) =>
    [
      i.group,
      i.name,
      i.sku,
      i.brand,
      originOf(i),
      i.qty,
      i.included ? 0 : i.unitUsd,
      lineTotal(i),
      i.vendor,
      i.buyUrl,
      i.process ?? "",
      i.materialName ?? "",
      i.tier,
    ]
      .map(csvCell)
      .join(","),
  );
  return [header.join(","), ...rows].join("\n");
}
