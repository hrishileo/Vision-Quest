export function originOf(item: BomItem): Origin {
  if (item.included) return "included";
  return item.origin ?? "buy";
}

export function lineTotal(item: BomItem) {
  if (item.included) return 0;
  return item.qty * item.unitUsd;
}

export function kitTotal(items: BomItem[]) {
  return items.reduce((s, it) => s + lineTotal(it), 0);
}

export function itemsForPart(partId: string) {
  return ITEMS.filter((it) => it.id === partId || it.catalogId === partId);
}

export type KitLabel = {
  title: string;
  sku: string;
  brand: string;
  group: string;
};

export function primaryItemForPart(partId: string): BomItem | undefined {
  const items = itemsForPart(partId);
  const exact = items.find((i) => i.id === partId);
  if (exact) return exact;
  const fly = items.filter((i) => i.tier !== "ground");
  const pool = fly.length ? fly : items;
  return (
    pool.find((i) => originOf(i) === "buy") ??
    pool.find((i) => originOf(i) === "included") ??
    pool[0]
  );
}

export function kitLabel(partId: string): KitLabel {
  const item = primaryItemForPart(partId);
  if (!item) {
    return { title: partId, sku: "", brand: "", group: "" };
  }
  return {
    title: item.name,
    sku: item.sku,
    brand: item.brand,
    group: item.group,
  };
}

